#!/usr/bin/env python3
"""Generate main/artwork.c from the canonical SVG assets.

Uses only the Python standard library so it works in ESP-IDF and PlatformIO
build environments without extra packages.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAIN = ROOT / "main"
THEMES = [
    ("CLASSIC_SVG", ROOT / "assets" / "classic-dark" / "screen.svg", "CONFIG_PANEL_THEME_CLASSIC"),
    ("SOCCER_SVG", ROOT / "assets" / "soccer-green" / "screen.svg", "CONFIG_PANEL_THEME_SOCCER"),
    ("KITTENS_SVG", ROOT / "assets" / "kittens-pink" / "screen.svg", "CONFIG_PANEL_THEME_KITTENS"),
    ("MAGIC_SVG", ROOT / "assets" / "magic-bricks-blue" / "screen.svg", "CONFIG_PANEL_THEME_MAGIC"),
]


def c_literal(text: str) -> str:
    lines = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
                .replace('"', '\\"')
                .replace("\r", "\\r")
                .replace("\n", "\\n")
        )
        lines.append(f'"{escaped}"')
    if not lines:
        lines.append('""')
    return "\n".join(lines)


def main() -> None:
    blocks = []
    for symbol, path, _ in THEMES:
        text = path.read_text(encoding="utf-8")
        blocks.append(f"static const char {symbol}[] =\n{c_literal(text)};\n")

    output = """/* AUTO-GENERATED by tools/generate_artwork.py. DO NOT EDIT. */
#include "artwork.h"
#include "sdkconfig.h"

""" + "\n".join(blocks) + """
artwork_svg_t artwork_get_active_svg(void)
{
#if CONFIG_PANEL_THEME_SOCCER
    return (artwork_svg_t){ (const uint8_t *)SOCCER_SVG, sizeof(SOCCER_SVG) - 1 };
#elif CONFIG_PANEL_THEME_KITTENS
    return (artwork_svg_t){ (const uint8_t *)KITTENS_SVG, sizeof(KITTENS_SVG) - 1 };
#elif CONFIG_PANEL_THEME_MAGIC
    return (artwork_svg_t){ (const uint8_t *)MAGIC_SVG, sizeof(MAGIC_SVG) - 1 };
#else
    return (artwork_svg_t){ (const uint8_t *)CLASSIC_SVG, sizeof(CLASSIC_SVG) - 1 };
#endif
}
"""

    (MAIN / "artwork.c").write_text(output, encoding="utf-8")
    print(f"Wrote {MAIN / 'artwork.c'}")


if __name__ == "__main__":
    main()
