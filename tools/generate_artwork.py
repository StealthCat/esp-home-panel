#!/usr/bin/env python3
"""Generate main/artwork.c from the canonical SVG theme assets.

This script uses only the Python standard library. PlatformIO executes it as a
pre-build script, and it can also be run directly.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAIN = ROOT / "main"
THEMES = [
    ("CLASSIC_SVG", ROOT / "assets" / "classic-dark" / "screen.svg"),
    ("SOCCER_SVG", ROOT / "assets" / "soccer-green" / "screen.svg"),
    ("KITTENS_SVG", ROOT / "assets" / "kittens-pink" / "screen.svg"),
    ("MAGIC_SVG", ROOT / "assets" / "magic-bricks-blue" / "screen.svg"),
]


def c_literal(text: str) -> str:
    lines = []
    for line in text.splitlines(keepends=True):
        escaped = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\r", "\\r")
            .replace("\n", "\\n")
        )
        lines.append(f'"{escaped}"')
    return "\n".join(lines) if lines else '""'


def generate() -> None:
    blocks = []
    for symbol, path in THEMES:
        text = path.read_text(encoding="utf-8")
        blocks.append(f"static const char {symbol}[] =\n{c_literal(text)};\n")

    output = """/* AUTO-GENERATED by tools/generate_artwork.py. DO NOT EDIT. */
#include "artwork.h"
#include "sdkconfig.h"

""" + "\n".join(blocks) + """
artwork_svg_t artwork_get_active_svg(void)
{
#if CONFIG_PANEL_THEME_SOCCER
    return (artwork_svg_t){ (const uint8_t *)SOCCER_SVG, sizeof(SOCCER_SVG) - 1 };
#elif CONFIG_PANEL_THEME_KITTENS
    return (artwork_svg_t){ (const uint8_t *)KITTENS_SVG, sizeof(KITTENS_SVG) - 1 };
#elif CONFIG_PANEL_THEME_MAGIC
    return (artwork_svg_t){ (const uint8_t *)MAGIC_SVG, sizeof(MAGIC_SVG) - 1 };
#else
    return (artwork_svg_t){ (const uint8_t *)CLASSIC_SVG, sizeof(CLASSIC_SVG) - 1 };
#endif
}
"""

    output_path = MAIN / "artwork.c"
    output_path.write_text(output, encoding="utf-8")
    print(f"[artwork] generated {output_path}")


generate()
